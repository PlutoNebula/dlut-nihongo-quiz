import re
p = r'^\*{0,2}\s*(单选题|多选题|判断题|填空题)\s*\*{0,2}\s*\*{0,2}\s*\d*\s*题?\s*\*{0,2}\s*$'
tests = [
    '**单选题** **9题**',
    '**多选题** **4题**',
    '**判断题** 2题',
    '**单选题** 12题',
    '**判断题**',
    '**填空题** 2题',
    '**单选题**',
    '**单选题** **12题**',
]
for t in tests:
    m = re.match(p, t)
    print('OK ' if m else 'MISS', repr(t))
